public class Variables {
    public static void main(String[] args) {
        // A variable is a named memory location used to store data.

        String name = "Gagan";
        /*
        String -> Datatype,
        name -> Variable name,
        "Gagan" -> Value

        This means we are storing the value ("Gagan") inside a memory location named (name).
         */
        System.out.println(name);

        int data = 20;
        /*
        int -> Datatype,
        data -> Variable name,
        20 -> Value

        This means we are storing the value (20) inside a memory location named (data).
         */
        System.out.println(data);
    }
}
